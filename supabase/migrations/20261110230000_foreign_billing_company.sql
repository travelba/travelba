  add column if not exists registration_number text;

comment on column public.crm_billing_companies.registration_number is
  'Identifiant d''entreprise hors SIRET (numéro de registre, NUI). Vide pour une société française.';

create unique index if not exists crm_billing_companies_registration_uidx
  on public.crm_billing_companies (customer_id, registration_number)
  where registration_number is not null;

